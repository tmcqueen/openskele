// Emits sdk/dotnet/Skele.Sdk/Generated/Protocol.g.cs: records and enums for
// the protocol payloads, method-name constants, and a System.Text.Json
// source-generation context so the SDK never needs reflection.

import { groups, refName, schemas, version, type Schema } from "./model";

const pascal = (name: string) =>
  name
    .split(/[^A-Za-z0-9]+/)
    .filter(Boolean)
    .map((part) => part[0].toUpperCase() + part.slice(1))
    .join("");

const summary = (text: string | undefined, indent: string) =>
  text ? `${indent}/// <summary>${text.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/\s*\n\s*/g, " ")}</summary>\n` : "";

function integer(format: string | undefined): string {
  switch (format) {
    case "uint32":
      return "uint";
    case "int64":
      return "long";
    case "uint64":
      return "ulong";
    default:
      return "int";
  }
}

/** The non-nullable C# type for a schema. */
function type(schema: Schema): string {
  if (schema === true) return "JsonElement";
  if (schema === false) throw new Error("`false` schemas have no C# type");
  if (schema.$ref) return refName(schema);
  if (schema.anyOf) {
    const present = schema.anyOf.filter((s: any) => s.type !== "null");
    if (present.length !== 1) throw new Error(`unsupported anyOf: ${JSON.stringify(schema)}`);
    return type(present[0]);
  }
  const kind = Array.isArray(schema.type) ? schema.type.find((t: string) => t !== "null") : schema.type;
  switch (kind) {
    case "string":
      return "string";
    case "integer":
      return integer(schema.format);
    case "number":
      return "double";
    case "boolean":
      return "bool";
    case "array":
      return `IReadOnlyList<${type(schema.items ?? true)}>`;
    case "object":
      return `IReadOnlyDictionary<string, ${type(schema.additionalProperties ?? true)}>`;
    case undefined:
      // No `type`: any JSON, like a `true` schema with a description or default.
      return "JsonElement";
    default:
      throw new Error(`unsupported schema: ${JSON.stringify(schema)}`);
  }
}

function record(name: string, schema: Record<string, any>): string {
  const required = new Set<string>(schema.required ?? []);
  const properties = Object.entries<Schema>(schema.properties ?? {});
  if (properties.length === 0) return `${summary(schema.description, "")}public sealed record ${name};`;

  const members = properties.map(([wire, prop]) => {
    const member = pascal(wire);
    if (member === name) throw new Error(`${name}.${wire} would collide with its record name`);
    const doc = typeof prop === "object" ? summary(prop.description, "    ") : "";
    const declaration = required.has(wire)
      ? `public required ${type(prop)} ${member} { get; init; }`
      : `public ${type(prop)}? ${member} { get; init; }`;
    return `${doc}    [JsonPropertyName(${JSON.stringify(wire)})]\n    ${declaration}`;
  });
  return `${summary(schema.description, "")}public sealed record ${name}\n{\n${members.join("\n\n")}\n}`;
}

function enumeration(name: string, schema: Record<string, any>): string {
  const members = schema.enum.map((value: string) => `    [JsonStringEnumMemberName(${JSON.stringify(value)})]\n    ${pascal(value)},`);
  return [
    `${summary(schema.description, "")}[JsonConverter(typeof(JsonStringEnumConverter<${name}>))]`,
    `public enum ${name}\n{\n${members.join("\n\n")}\n}`,
  ].join("\n");
}

export function emitCsharp(): string {
  const out: string[] = [
    "// <auto-generated>",
    "// Generated by scripts/gen-sdk.ts from protocol/openrpc.json. Do not edit.",
    "// </auto-generated>",
    "#nullable enable",
    "",
    "using System.Text.Json;",
    "using System.Text.Json.Serialization;",
    "",
    "namespace Skele.Sdk.Protocol;",
    "",
    "public static class ProtocolInfo",
    "{",
    `    public const string Version = ${JSON.stringify(version)};`,
    "}",
    "",
  ];

  for (const [name, schema] of schemas) {
    if (schema.enum) out.push(enumeration(name, schema), "");
    else if (schema.type === "object") out.push(record(name, schema), "");
    else throw new Error(`unsupported top-level schema ${name}`);
  }

  out.push("/// <summary>Method names, grouped by which side sends them.</summary>", "public static class Methods", "{");
  for (const sender of ["host", "plugin"] as const) {
    const methods = groups.filter((g) => g.sender === sender).flatMap((g) => g.methods);
    out.push(
      `    /// <summary>Sent by the ${sender}.</summary>`,
      `    public static class ${pascal(sender)}`,
      "    {",
      ...methods.map((m) => `        public const string ${pascal(m.name)} = ${JSON.stringify(m.name)};`),
      "    }",
      "",
    );
  }
  out.pop();
  out.push("}", "");

  out.push(
    "[JsonSourceGenerationOptions(DefaultIgnoreCondition = JsonIgnoreCondition.WhenWritingNull)]",
    ...schemas.map(([name]) => `[JsonSerializable(typeof(${name}))]`),
    "[JsonSerializable(typeof(JsonElement))]",
    "public sealed partial class ProtocolJsonContext : JsonSerializerContext;",
    "",
  );
  return out.join("\n");
}
