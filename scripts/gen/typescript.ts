// Emits sdk/typescript/src/generated/protocol.ts.

import { groups, refName, schemas, version, type Schema } from "./model";

const comment = (text: string | undefined, indent = "") =>
  text ? `${indent}/** ${text.replace(/\*\//g, "*\\/").replace(/\s*\n\s*/g, " ")} */\n` : "";

function type(schema: Schema): string {
  if (schema === true) return "unknown";
  if (schema === false) return "never";
  if (schema.$ref) return refName(schema);
  if (schema.anyOf) return schema.anyOf.map(type).join(" | ");
  if (schema.enum) return schema.enum.map((v: unknown) => JSON.stringify(v)).join(" | ");
  if (Array.isArray(schema.type)) return schema.type.map((t: string) => type({ ...schema, type: t })).join(" | ");
  switch (schema.type) {
    case "string":
      return "string";
    case "integer":
    case "number":
      return "number";
    case "boolean":
      return "boolean";
    case "null":
      return "null";
    case "array":
      return `${wrap(type(schema.items ?? true))}[]`;
    case "object":
      if (schema.properties) return object(schema, "  ");
      return `Record<string, ${type(schema.additionalProperties ?? true)}>`;
    default:
      return "unknown";
  }
}

const wrap = (t: string) => (t.includes(" ") ? `(${t})` : t);

function object(schema: Record<string, any>, indent: string): string {
  const required = new Set<string>(schema.required ?? []);
  const fields = Object.entries<Schema>(schema.properties ?? {}).map(([name, prop]) => {
    const doc = typeof prop === "object" ? comment(prop.description, indent) : "";
    // Optional on the wire means absent or null, so drop the explicit null.
    const t = required.has(name) ? type(prop) : type(prop).replace(/ \| null$/, "");
    return `${doc}${indent}${name}${required.has(name) ? "" : "?"}: ${t};`;
  });
  return fields.length ? `{\n${fields.join("\n")}\n${indent.slice(2)}}` : "Record<string, never>";
}

export function emitTypescript(): string {
  const out: string[] = [
    "// Generated by scripts/gen-sdk.ts from protocol/openrpc.json. Do not edit.",
    "",
    `export const PROTOCOL_VERSION = ${JSON.stringify(version)};`,
    "",
  ];

  for (const [name, schema] of schemas) {
    const body = schema.type === "object" ? object(schema, "  ") : type(schema);
    const decl =
      schema.type === "object" && schema.properties ? `export interface ${name} ${body}` : `export type ${name} = ${body};`;
    out.push(comment(schema.description) + decl, "");
  }

  for (const group of groups) {
    const lines = group.methods.map((m) =>
      group.kind === "request"
        ? `  ${JSON.stringify(m.name)}: { params: ${type(m.params)}; result: ${type(m.result!)} };`
        : `  ${JSON.stringify(m.name)}: ${type(m.params)};`,
    );
    out.push(`${comment(group.doc)}export interface ${group.name} {\n${lines.join("\n")}\n}`, "");
  }
  return out.join("\n");
}
