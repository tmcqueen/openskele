// Generates the TypeScript SDK's protocol types from protocol/openrpc.json.
// Handles the subset of JSON Schema that the protocol document uses.

import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

type Schema = boolean | Record<string, any>;

const root = join(import.meta.dir, "..");
const doc = JSON.parse(readFileSync(join(root, "protocol/openrpc.json"), "utf8"));

const comment = (text: string | undefined, indent = "") =>
  text ? `${indent}/** ${text.replace(/\*\//g, "*\\/").replace(/\s*\n\s*/g, " ")} */\n` : "";

function type(schema: Schema): string {
  if (schema === true) return "unknown";
  if (schema === false) return "never";
  if (schema.$ref) return schema.$ref.split("/").pop();
  if (schema.anyOf) return schema.anyOf.map(type).join(" | ");
  if (schema.enum) return schema.enum.map((v: unknown) => JSON.stringify(v)).join(" | ");
  if (Array.isArray(schema.type)) return schema.type.map((t: string) => type({ ...schema, type: t })).join(" | ");
  switch (schema.type) {
    case "string":
      return "string";
    case "integer":
    case "number":
      return "number";
    case "boolean":
      return "boolean";
    case "null":
      return "null";
    case "array":
      return `${wrap(type(schema.items ?? true))}[]`;
    case "object":
      if (schema.properties) return object(schema, "  ");
      return `Record<string, ${type(schema.additionalProperties ?? true)}>`;
    default:
      return "unknown";
  }
}

const wrap = (t: string) => (t.includes(" ") ? `(${t})` : t);

function object(schema: Record<string, any>, indent: string): string {
  const required = new Set<string>(schema.required ?? []);
  const fields = Object.entries<Schema>(schema.properties ?? {}).map(([name, prop]) => {
    const doc = typeof prop === "object" ? comment(prop.description, indent) : "";
    // Optional on the wire means absent or null, so drop the explicit null.
    const t = required.has(name) ? type(prop) : type(prop).replace(/ \| null$/, "");
    return `${doc}${indent}${name}${required.has(name) ? "" : "?"}: ${t};`;
  });
  return fields.length ? `{\n${fields.join("\n")}\n${indent.slice(2)}}` : "Record<string, never>";
}

const out: string[] = [
  "// Generated by scripts/gen-sdk.ts from protocol/openrpc.json. Do not edit.",
  "",
  `export const PROTOCOL_VERSION = ${JSON.stringify(doc.info.version)};`,
  "",
];

for (const [name, schema] of Object.entries<Record<string, any>>(doc.components.schemas)) {
  const body = schema.type === "object" ? object(schema, "  ") : type(schema);
  const decl = schema.type === "object" && schema.properties ? `export interface ${name} ${body}` : `export type ${name} = ${body};`;
  out.push(comment(schema.description) + decl, "");
}

const maps: [string, string, string, string][] = [
  ["HostRequests", "Requests the host sends; a plugin answers them.", "hostToPlugin", "request"],
  ["HostNotifications", "Notifications the host sends.", "hostToPlugin", "notification"],
  ["PluginRequests", "Requests a plugin may send to the host.", "pluginToHost", "request"],
  ["PluginNotifications", "Notifications a plugin may send to the host.", "pluginToHost", "notification"],
];
for (const [name, doc_, direction, kind] of maps) {
  const methods = doc.methods.filter((m: any) => m["x-direction"] === direction && m["x-kind"] === kind);
  const lines = methods.map((m: any) =>
    kind === "request"
      ? `  ${JSON.stringify(m.name)}: { params: ${type(m["x-params"])}; result: ${type(m.result.schema)} };`
      : `  ${JSON.stringify(m.name)}: ${type(m["x-params"])};`,
  );
  out.push(`${comment(doc_)}export interface ${name} {\n${lines.join("\n")}\n}`, "");
}

const target = join(root, "sdk/typescript/src/generated/protocol.ts");
writeFileSync(target, out.join("\n"));
console.log("wrote sdk/typescript/src/generated/protocol.ts");
